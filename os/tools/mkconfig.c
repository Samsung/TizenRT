/****************************************************************************
 * Included Files
 ****************************************************************************/

#include <string.h>
#include <stdlib.h>
#include <errno.h>

#include "cfgdefine.h"

/****************************************************************************
 * Pre-processor Definitions
 ****************************************************************************/

#define DEFCONFIG ".config"

/****************************************************************************
 * Private Functions
 ****************************************************************************/

static inline char *getfilepath(const char *name)
{
	char *line = get_line_ptr();

	snprintf(line, PATH_MAX, "%s/" DEFCONFIG, name);
	line[PATH_MAX] = '\0';
	return strdup(line);
}

static void show_usage(const char *progname)
{
	fprintf(stderr, "USAGE: %s <abs path to .config>\n", progname);
	exit(1);
}

/****************************************************************************
 * Public Functions
 ****************************************************************************/

int main(int argc, char **argv, char **envp)
{
	char *filepath;
	FILE *stream;

	if (argc != 2) {
		fprintf(stderr, "Unexpected number of arguments\n");
		show_usage(argv[0]);
	}

	filepath = getfilepath(argv[1]);
	if (!filepath) {
		fprintf(stderr, "getfilepath failed\n");
		exit(2);
	}

	stream = fopen(filepath, "r");
	if (!stream) {
		fprintf(stderr, "open %s failed: %s\n", filepath, strerror(errno));
		exit(3);
	}

	printf("/* config.h -- Autogenerated! Do not edit. */\n\n");
	printf("#ifndef __INCLUDE_CONFIG_H\n");
	printf("#define __INCLUDE_CONFIG_H\n\n");
	printf("/* Used to represent the values of tristate options */\n\n");
	printf("#define CONFIG_y 1\n");
	printf("#define CONFIG_m 2\n\n");
	printf("/* General Definitions ***********************************/\n");
	generate_definitions(stream);
	printf("\n/* Sanity Checks *****************************************/\n\n");
	printf("/* If the end of RAM is not specified then it is assumed to be\n");
	printf(" * the beginning of RAM plus the RAM size.\n");
	printf(" */\n\n");
	printf("#ifndef CONFIG_RAM_END\n");
	printf("#  define CONFIG_RAM_END (CONFIG_RAM_START+CONFIG_RAM_SIZE)\n");
	printf("#endif\n\n");
	printf("#ifndef CONFIG_RAM_VEND\n");
	printf("#  define CONFIG_RAM_VEND (CONFIG_RAM_VSTART+CONFIG_RAM_SIZE)\n");
	printf("#endif\n\n");
	printf("/* If the end of FLASH is not specified then it is assumed to be\n");
	printf(" * the beginning of FLASH plus the FLASH size.\n");
	printf(" */\n\n");
	printf("#ifndef CONFIG_FLASH_END\n");
	printf("#  define CONFIG_FLASH_END (CONFIG_FLASH_START+CONFIG_FLASH_SIZE)\n");
	printf("#endif\n\n");
	printf("/* TizenRT board options *********************************/\n\n");
	printf("/* If no board crashdump mechanism's are enabled,\n");
	printf(" * then let's disable the board crashdump itself\n");
	printf(" */\n\n");
	printf("#if !defined(CONFIG_BOARD_DUMP_UART) && \\\n");
	printf("    !defined(CONFIG_BOARD_RAMDUMP_FLASH) && \\\n");
	printf("    !defined(CONFIG_BOARD_COREDUMP_FLASH)\n");
	printf("# undef CONFIG_BOARD_CRASHDUMP\n");
	printf("#endif\n\n");
	printf("/* We need the flash start address to calculate the offset for the Userfs partition */\n");
	printf("#if defined(CONFIG_BOARD_DUMP_UART)\n");
	printf("# if CONFIG_ARCH_BOARD_ARTIK05X_FAMILY == 1\n");
	printf("#  define CONFIG_FLASH_START_ADDR 0x04000000\n");
	printf("# elif (CONFIG_ARCH_BOARD_IMXRT1050_EVK == 1  || CONFIG_ARCH_BOARD_IMXRT1020_EVK == 1)\n");
	printf("#  define CONFIG_FLASH_START_ADDR 0x60000000\n");
	printf("# elif CONFIG_ARCH_BOARD_ESP32_FAMILY == 1\n");
	printf("#  define CONFIG_FLASH_START_ADDR 0x300000\n");
	printf("# elif CONFIG_ARCH_BOARD_RTL8721CSM == 1\n");
	printf("#  define CONFIG_FLASH_START_ADDR 0x8000000\n");
	printf("# elif CONFIG_ARCH_BOARD_SIDK_S5JT200 == 1\n");
	printf("#  define CONFIG_FLASH_START_ADDR 0x040C8000\n");
	printf("# elif (CONFIG_ARCH_BOARD_STM32F407_DISC1 == 1 || CONFIG_ARCH_BOARD_STM32F429I_DISCO == 1 || CONFIG_ARCH_BOARD_STM32L4R9AI_DISCO == 1)\n");
	printf("#  define CONFIG_FLASH_START_ADDR 0x08000000\n");
	printf("# elif CONFIG_ARCH_BOARD_MT7686_HDK == 1\n");
	printf("#  define CONFIG_FLASH_START_ADDR 0x8000000\n");
	printf("# else\n");
	printf("#  define CONFIG_FLASH_START_ADDR -1\n");
	printf("# endif\n");
	printf("#endif\n\n");
	printf("/* There must be at least one memory region. */\n\n");
	printf("#ifndef CONFIG_KMM_REGIONS\n");
	printf("# define CONFIG_KMM_REGIONS 1\n");
	printf("#endif\n\n");
	printf("/* If the end of FLASH is not specified then it is assumed to be the beginning\n");
	printf(" * of FLASH plus the FLASH size.\n");
	printf(" */\n\n");
	printf("#ifndef CONFIG_FLASH_END_ADDR\n");
	printf("#define CONFIG_FLASH_END_ADDR (CONFIG_FLASH_START_ADDR + CONFIG_FLASH_SIZE)\n");
	printf("#endif\n\n");
	printf("#if defined(CONFIG_MPU_STACK_OVERFLOW_PROTECTION)\n");
	printf("# if (CONFIG_MPU_STACK_GUARD_SIZE != 32) && \\\n");
	printf("    (CONFIG_MPU_STACK_GUARD_SIZE != 64) && \\\n");
	printf("    (CONFIG_MPU_STACK_GUARD_SIZE != 128) && \\\n");
	printf("    (CONFIG_MPU_STACK_GUARD_SIZE != 256) && \\\n");
	printf("    (CONFIG_MPU_STACK_GUARD_SIZE != 512) && \\\n");
	printf("    (CONFIG_MPU_STACK_GUARD_SIZE != 1024) \n");
	printf("#  define CONFIG_MPU_STACK_GUARD_SIZE 32\n");
	printf("# endif\n");
	printf("#endif\n\n");
	printf("#endif /* __INCLUDE_CONFIG_H */\n");
	fclose(stream);

	/* Exit (without bothering to clean up allocations) */

	free(filepath);
	return 0;
}
